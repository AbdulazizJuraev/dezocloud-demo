/** Dialog ochadi; yopish funksiyasi bilan elementni qaytaradi. */
export function modal(html) {
  const back = document.createElement('div');
  back.className = 'modal-back';
  back.innerHTML = `<div class="modal" role="dialog" aria-modal="true">${html}</div>`;
  const close = () => { back.remove(); document.removeEventListener('keydown', onKey, true); };
  const onKey = (e) => { if (e.key === 'Escape') { e.stopPropagation(); close(); } };
  document.addEventListener('keydown', onKey, true);
  back.addEventListener('mousedown', (e) => { if (e.target === back) close(); });
  document.getElementById('overlay-root').appendChild(back);
  const el = back.firstElementChild;
  el.close = close;
  hydrateIcons(el);
  return el;
}

/** Matn so'raydi. */
export function promptText({ title, label, value = '', ok = 'Saqlash', max = 120 }) {
  return new Promise((resolve) => {
    const m = modal(`
      <h2>${esc(title)}</h2>
      <label class="field"><span>${esc(label)}</span><input id="pt" maxlength="${max}" value="${esc(value)}"></label>
      <div class="actions"><button class="btn" data-x="c">Bekor</button><button class="btn primary" data-x="ok">${esc(ok)}</button></div>`);
    const input = $('#pt', m);
    input.focus(); input.select();
    const done = (v) => { m.close(); resolve(v); };
    $('[data-x="c"]', m).onclick = () => done(null);
    $('[data-x="ok"]', m).onclick = () => done(input.value.trim());
    input.onkeydown = (e) => { if (e.key === 'Enter') done(input.value.trim()); };
  });
}

export function confirmBox({ title, text = '', ok = 'Ha', danger = false }) {
  return new Promise((resolve) => {
    const m = modal(`
      <h2>${esc(title)}</h2>${text ? `<div class="muted" style="color:var(--muted)">${esc(text)}</div>` : ''}
      <div class="actions"><button class="btn" data-x="c">Bekor</button>
      <button class="btn primary${danger ? ' danger' : ''}" data-x="ok"${danger ? ' style="background:var(--danger);color:#fff"' : ''}>${esc(ok)}</button></div>`);
    $('[data-x="ok"]', m).focus();
    $('[data-x="c"]', m).onclick = () => { m.close(); resolve(false); };
    $('[data-x="ok"]', m).onclick = () => { m.close(); resolve(true); };
  });
}

// ── Menyu (qalqib chiqadigan) ─────────────────────────────────────
export function openMenu(anchor, html) {
  document.querySelector('.menu')?.remove();
  const m = document.createElement('div');
  m.className = 'menu';
  m.innerHTML = html;
  document.body.appendChild(m);
  hydrateIcons(m);

  const r = anchor.getBoundingClientRect();
  const w = m.offsetWidth, h = m.offsetHeight;
  m.style.left = `${Math.max(8, Math.min(r.right - w, innerWidth - w - 8))}px`;
  m.style.top = `${r.bottom + h + 8 > innerHeight ? Math.max(8, r.top - h - 4) : r.bottom + 4}px`;

  const close = () => { m.remove(); document.removeEventListener('mousedown', away, true); document.removeEventListener('keydown', onKey, true); };
  const away = (e) => { if (!m.contains(e.target)) close(); };
  const onKey = (e) => { if (e.key === 'Escape') close(); };
  setTimeout(() => { document.addEventListener('mousedown', away, true); document.addEventListener('keydown', onKey, true); });
  m.close = close;
  m.addEventListener('click', (e) => { if (e.target.closest('button,a')) setTimeout(close); });
  return m;
}

export async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    const ta = document.createElement('textarea');
    ta.value = text; ta.style.position = 'fixed'; ta.style.opacity = '0';
    document.body.appendChild(ta); ta.select();
    let ok = false;
    try { ok = document.execCommand('copy'); } catch {}
    ta.remove();
    return ok;
  }
}
