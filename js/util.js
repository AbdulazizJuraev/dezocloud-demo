// ── Formatlar ─────────────────────────────────────────────────────
export function bytes(n) {
  if (!n) return '0 B';
  const u = ['B', 'KB', 'MB', 'GB', 'TB'];
  const i = Math.min(Math.floor(Math.log(n) / Math.log(1024)), u.length - 1);
  const v = n / 1024 ** i;
  return `${v >= 100 || i === 0 ? Math.round(v) : v.toFixed(1)} ${u[i]}`;
}

export function duration(sec) {
  if (!sec || !Number.isFinite(sec)) return '';
  const s = Math.round(sec);
  const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), r = s % 60;
  return h ? `${h}:${String(m).padStart(2, '0')}:${String(r).padStart(2, '0')}` : `${m}:${String(r).padStart(2, '0')}`;
}

const MONTHS = ['yanvar', 'fevral', 'mart', 'aprel', 'may', 'iyun', 'iyul', 'avgust', 'sentabr', 'oktyabr', 'noyabr', 'dekabr'];
const DAYS = ['yakshanba', 'dushanba', 'seshanba', 'chorshanba', 'payshanba', 'juma', 'shanba'];

export const dayKey = (ts) => { const d = new Date(ts); return `${d.getFullYear()}-${d.getMonth()}-${d.getDate()}`; };

export const monthKey = (ts) => { const d = new Date(ts); return `${d.getFullYear()}-${d.getMonth()}`; };

export function monthLabel(ts) {
  const d = new Date(ts);
  const name = MONTHS[d.getMonth()];
  const title = name[0].toUpperCase() + name.slice(1);
  return d.getFullYear() === new Date().getFullYear() ? title : `${title} ${d.getFullYear()}`;
}

export function dayLabel(ts) {
  const d = new Date(ts);
  const now = new Date();
  const mid = (x) => new Date(x.getFullYear(), x.getMonth(), x.getDate()).getTime();
  const diff = Math.round((mid(now) - mid(d)) / 86_400_000);
  if (diff === 0) return 'Bugun';
  if (diff === 1) return 'Kecha';
  const base = `${d.getDate()}-${MONTHS[d.getMonth()]}`;
  return d.getFullYear() === now.getFullYear() ? `${base}, ${DAYS[d.getDay()]}` : `${base}, ${d.getFullYear()}`;
}

export function fullDate(ts) {
  const d = new Date(ts);
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getDate()}-${MONTHS[d.getMonth()]} ${d.getFullYear()}, ${DAYS[d.getDay()]}, ${p(d.getHours())}:${p(d.getMinutes())}`;
}

// ── API ───────────────────────────────────────────────────────────
export async function api(url, { method = 'GET', body } = {}) {
  const res = await fetch(url, {
    method,
    headers: body ? { 'Content-Type': 'application/json' } : undefined,
    body: body ? JSON.stringify(body) : undefined,
  });
  if (res.status === 401) { location.href = './login.html'; throw new Error('Kirish talab qilinadi'); }
  const data = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(data.error || `Xato ${res.status}`);
  return data;
}

